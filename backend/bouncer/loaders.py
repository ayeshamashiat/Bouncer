"""CSV -> FalkorDB. Idempotent: every write is a MERGE on the key property only,
then SET for the rest, so running it twice gives the same graph.

Run from backend/:
    python -m bouncer.loaders ../data/            # Mrittika's real data
    python -m bouncer.loaders ../data/sample/     # our synthetic sample
    python -m bouncer.loaders ../data/ --reset    # wipe the graph first
"""
import csv
import sys
from collections import defaultdict
from pathlib import Path

from .db import get_graph, graph_name
from .categories import categories_for
from .defang import (LIVE_IP_RE, LIVE_URL_RE, canon_domain, canon_ip, canon_payload,
                     is_common_infra_domain)
from .schema import create_indexes

SKILL_COLS = ["skill_name", "publisher", "published_at", "status", "campaign", "source_report", "synthetic"]
INFRA_COLS = ["skill_name", "kind", "value_defanged", "source_report"]
LEGIT_COLS = ["skill_name", "publisher", "published_at", "source_url"]
DEMO_COLS = ["skill_name", "publisher", "expected_verdict", "scene", "text_file"]
RESOLVE_COLS = ["domain", "ip", "source_report"]  # optional file: resolutions.csv

SYNTHETIC_REPORT = {"id": "synthetic", "title": "Synthetic rows generated by the team",
                    "url": "synthetic", "what": "made-up skills attached to real infrastructure"}

# A domain/IP used by at least this many trusted (legit) skills is treated as a supernode.
SUPERNODE_MIN_TRUSTED = 3


# ---------------------------------------------------------------- reading

def _read_csv(path: Path) -> list[dict]:
    if not path.exists():
        return []
    with path.open(newline="", encoding="utf-8") as f:
        return [{k.strip(): (v or "").strip() for k, v in row.items() if k} for row in csv.DictReader(f)]


def _columns(path: Path) -> list[str]:
    with path.open(newline="", encoding="utf-8") as f:
        return [c.strip() for c in (next(csv.reader(f), []) or [])]


def _truthy(v: str) -> bool:
    return v.strip().lower() in {"true", "1", "yes", "y"}


def read_sources(path: Path) -> list[dict]:
    """sources.md: one line per report:  id | title | url | what was taken."""
    out = []
    if not path.exists():
        return out
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip().strip("-* ").strip()
        if "|" not in line or set(line) <= set("|-: "):
            continue
        parts = [p.strip() for p in line.strip("|").split("|")]
        if len(parts) < 3 or parts[0].lower() in {"id", "short id"}:
            continue
        out.append({"id": parts[0], "title": parts[1], "url": parts[2],
                    "what": parts[3] if len(parts) > 3 else ""})
    return out


def read_all(data_dir: Path) -> dict:
    d = Path(data_dir)
    return {
        "skills": _read_csv(d / "skills.csv"),
        "infra": _read_csv(d / "infra.csv"),
        "legit": _read_csv(d / "legit.csv"),
        "demo": _read_csv(d / "demo" / "demo_items.csv"),
        "resolutions": _read_csv(d / "resolutions.csv"),
        "sources": read_sources(d / "sources.md"),
    }


# ---------------------------------------------------------------- validation

def validate(data_dir) -> list[str]:
    d = Path(data_dir)
    errors: list[str] = []
    for name, cols in [("skills.csv", SKILL_COLS), ("infra.csv", INFRA_COLS), ("legit.csv", LEGIT_COLS)]:
        p = d / name
        if not p.exists():
            errors.append(f"{name}: file missing")
            continue
        missing = [c for c in cols if c not in _columns(p)]
        if missing:
            errors.append(f"{name}: missing columns {missing}")
    if not (d / "sources.md").exists():
        errors.append("sources.md: file missing")
    for name, cols in [("demo/demo_items.csv", DEMO_COLS), ("resolutions.csv", RESOLVE_COLS)]:
        p = d / name
        if p.exists():
            missing = [c for c in cols if c not in _columns(p)]
            if missing:
                errors.append(f"{name}: missing columns {missing}")
    if errors:
        return errors

    data = read_all(d)
    source_ids = {s["id"] for s in data["sources"]} | {"synthetic"}

    def check_live(file, line, field, value):
        if LIVE_URL_RE.search(value) or LIVE_IP_RE.search(value):
            errors.append(f"{file}:{line}: {field} is not defanged: {value!r}")

    def check_source(file, line, row):
        src, syn = row.get("source_report", ""), _truthy(row.get("synthetic", ""))
        if not src and not syn:
            errors.append(f"{file}:{line}: needs source_report or synthetic=true")
        elif src and src not in source_ids:
            errors.append(f"{file}:{line}: source_report {src!r} is not listed in sources.md")

    seen: dict[str, str] = {}
    for i, r in enumerate(data["skills"], start=2):
        n = r["skill_name"]
        if not n:
            errors.append(f"skills.csv:{i}: empty skill_name")
            continue
        if n in seen:
            errors.append(f"skills.csv:{i}: duplicate skill_name {n!r} (also in {seen[n]})")
        seen[n] = "skills.csv"
        if r["status"] not in {"known_bad", "unknown", "trusted"}:
            errors.append(f"skills.csv:{i}: status must be known_bad|unknown|trusted, got {r['status']!r}")
        for f in ("skill_name", "publisher", "campaign"):
            check_live("skills.csv", i, f, r[f])
        check_source("skills.csv", i, r)

    for i, r in enumerate(data["legit"], start=2):
        n = r["skill_name"]
        if n in seen:
            errors.append(f"legit.csv:{i}: duplicate skill_name {n!r} (also in {seen[n]})")
        seen[n] = "legit.csv"
        if not r["source_url"]:
            errors.append(f"legit.csv:{i}: needs source_url")
        check_live("legit.csv", i, "skill_name", n)

    demo_names = {r["skill_name"] for r in data["demo"]}
    for i, r in enumerate(data["demo"], start=2):
        if r["expected_verdict"] not in {"ALLOW", "ASK", "BLOCK"}:
            errors.append(f"demo_items.csv:{i}: expected_verdict must be ALLOW|ASK|BLOCK")

    for i, r in enumerate(data["infra"], start=2):
        if r["skill_name"] not in seen and r["skill_name"] not in demo_names:
            errors.append(f"infra.csv:{i}: skill {r['skill_name']!r} not in skills/legit/demo")
        if r["kind"] not in {"domain", "ip", "payload"}:
            errors.append(f"infra.csv:{i}: kind must be domain|ip|payload, got {r['kind']!r}")
        check_live("infra.csv", i, "value_defanged", r["value_defanged"])
        if r["kind"] == "ip":
            try:
                canon_ip(r["value_defanged"])
            except ValueError:
                errors.append(f"infra.csv:{i}: not an IP: {r['value_defanged']!r}")
        if not r["value_defanged"]:
            errors.append(f"infra.csv:{i}: empty value_defanged")
        check_source("infra.csv", i, {"source_report": r["source_report"],
                                      "synthetic": "true" if r["source_report"] == "synthetic" else ""})

    for i, r in enumerate(data["resolutions"], start=2):
        for f in ("domain", "ip"):
            check_live("resolutions.csv", i, f, r[f])
        check_source("resolutions.csv", i, {"source_report": r["source_report"],
                                            "synthetic": "true" if r["source_report"] == "synthetic" else ""})
    return errors


# ---------------------------------------------------------------- loading

def _report_url(source_id: str, sources: dict) -> str:
    if not source_id or source_id == "synthetic":
        return "synthetic"
    return sources.get(source_id, {}).get("url") or f"source:{source_id}"


def _common_infra(data) -> set[tuple[str, str]]:
    """(kind, canonical value) pairs that become CommonInfra: allowlist + degree check."""
    trusted = {r["skill_name"] for r in data["legit"]}
    users = defaultdict(set)
    out = set()
    for r in data["infra"]:
        if r["kind"] == "domain":
            v = canon_domain(r["value_defanged"])
            if is_common_infra_domain(v):
                out.add(("domain", v))
        elif r["kind"] == "ip":
            v = canon_ip(r["value_defanged"])
        else:
            continue
        if r["skill_name"] in trusted:
            users[(r["kind"], v)].add(r["skill_name"])
    out |= {k for k, s in users.items() if len(s) >= SUPERNODE_MIN_TRUSTED}
    return out


def load_all(data_dir, g=None, reset: bool = False) -> dict:
    errors = validate(data_dir)
    if errors:
        raise ValueError("validation failed:\n  " + "\n  ".join(errors))
    g = g or get_graph()
    if reset:
        try:
            g.delete()
        except Exception:
            pass
    create_indexes(g)
    data = read_all(Path(data_dir))
    sources = {s["id"]: s for s in data["sources"]}
    sources["synthetic"] = SYNTHETIC_REPORT

    # Reports
    g.query("UNWIND $rows AS r MERGE (x:Report {url: r.url}) SET x.title = r.title, x.source_id = r.id, x.what = r.what",
            {"rows": list(sources.values())})

    # Campaigns + Publishers + malicious/listed skills
    skills = [{
        "name": r["skill_name"], "publisher": r["publisher"], "published_at": r["published_at"],
        "status": r["status"], "campaign": r["campaign"], "synthetic": _truthy(r["synthetic"]),
        "report": _report_url(r["source_report"], sources),  # empty source -> the synthetic report
    } for r in data["skills"]]
    g.query("""
        UNWIND $rows AS r
        MERGE (s:Skill {name: r.name})
        SET s.status = r.status, s.published_at = r.published_at, s.campaign = r.campaign,
            s.synthetic = r.synthetic
        WITH s, r
        // An empty publisher (a report that redacts it) gets no Publisher node: a shared "" node
        // would link every redacted skill to every other one.
        FOREACH (_ IN CASE WHEN r.publisher = '' THEN [] ELSE [1] END |
            MERGE (p:Publisher {handle: r.publisher})
            SET p.platform = 'clawhub'
            MERGE (s)-[:PUBLISHED_BY]->(p))
        WITH s, r
        MATCH (rep:Report {url: r.report})
        MERGE (s)-[:SOURCED_FROM]->(rep)
    """, {"rows": skills})
    g.query("""
        UNWIND $rows AS r
        WITH r WHERE r.status = 'known_bad' AND r.campaign <> ''
        MATCH (s:Skill {name: r.name})
        MERGE (c:Campaign {name: r.campaign})
        MERGE (s)-[:PART_OF]->(c)
    """, {"rows": skills})
    g.query("""
        MATCH (c:Campaign)<-[:PART_OF]-(s:Skill)
        WITH c, min(s.published_at) AS first
        SET c.first_seen = first
    """)

    # Legitimate skills
    legit = [{"name": r["skill_name"], "publisher": r["publisher"], "published_at": r["published_at"],
              "source_url": r["source_url"]} for r in data["legit"]]
    g.query("""
        UNWIND $rows AS r
        MERGE (s:Skill {name: r.name})
        SET s.status = 'trusted', s.published_at = r.published_at, s.synthetic = (r.source_url = 'synthetic'),
            s.source_url = r.source_url
        MERGE (p:Publisher {handle: r.publisher})
        SET p.platform = 'clawhub'
        MERGE (s)-[:PUBLISHED_BY]->(p)
    """, {"rows": legit})

    # Demo items: only those with a publisher are "already seen" by Bouncer.
    # An empty publisher means a brand-new, never-seen item (Scene 2 investigator story).
    demo = [{"name": r["skill_name"], "publisher": r["publisher"]} for r in data["demo"] if r["publisher"]]
    g.query("""
        UNWIND $rows AS r
        MERGE (s:Skill {name: r.name})
        ON CREATE SET s.status = 'unknown', s.synthetic = true, s.demo = true
        MERGE (p:Publisher {handle: r.publisher})
        SET p.platform = coalesce(p.platform, 'clawhub')
        MERGE (s)-[:PUBLISHED_BY]->(p)
    """, {"rows": demo})

    # Publisher first_seen = earliest skill they published (proxy for account age)
    g.query("""
        MATCH (p:Publisher)<-[:PUBLISHED_BY]-(s:Skill)
        WITH p, min(s.published_at) AS first
        SET p.first_seen = first
    """)

    # Infrastructure: split by label (labels cannot be query parameters)
    common = _common_infra(data)
    buckets = defaultdict(list)
    for r in data["infra"]:
        kind = r["kind"]
        if kind == "domain":
            v = canon_domain(r["value_defanged"])
        elif kind == "ip":
            v = canon_ip(r["value_defanged"])
        else:
            v = canon_payload(r["value_defanged"])
        is_common = (kind, v) in common
        buckets[(kind, is_common)].append({
            "skill": r["skill_name"], "value": v, "kind": kind,
            "report": _report_url(r["source_report"], sources),
        })
    for (kind, is_common), rows in buckets.items():
        g.query(_INFRA_QUERIES[(kind, is_common)], {"rows": rows})

    # Optional passive-DNS style facts: domain -> ip
    res_rows = []
    for r in data["resolutions"]:
        d, ip = canon_domain(r["domain"]), canon_ip(r["ip"])
        res_rows.append({"domain": d, "ip": ip, "report": _report_url(r["source_report"], sources),
                         "d_common": ("domain", d) in common, "ip_common": ("ip", ip) in common})
    for flags, q in _RESOLVE_QUERIES.items():
        rows = [r for r in res_rows if (r["d_common"], r["ip_common"]) == flags]
        if rows:
            g.query(q, {"rows": rows})

    # Categories (for suggesting safer alternatives); never used as evidence
    names = [r[0] for r in g.query("MATCH (s:Skill) RETURN s.name").result_set]
    g.query(_CATEGORY_QUERY, {"rows": [{"name": n, "cats": categories_for(n)} for n in names if categories_for(n)]})

    return counts(g)


_CATEGORY_QUERY = """
UNWIND $rows AS r
MATCH (s:Skill {name: r.name})
UNWIND r.cats AS c
MERGE (k:Category {name: c})
MERGE (s)-[:IN_CATEGORY]->(k)
"""

_INFRA_QUERIES = {
    ("domain", False): """
        UNWIND $rows AS r MATCH (s:Skill {name: r.skill}) MATCH (rep:Report {url: r.report})
        MERGE (x:Domain {name: r.value}) MERGE (s)-[:CONTACTS]->(x) MERGE (x)-[:SOURCED_FROM]->(rep)""",
    ("domain", True): """
        UNWIND $rows AS r MATCH (s:Skill {name: r.skill}) MATCH (rep:Report {url: r.report})
        MERGE (x:CommonInfra {name: r.value}) SET x.kind = 'Domain'
        MERGE (s)-[:CONTACTS]->(x) MERGE (x)-[:SOURCED_FROM]->(rep)""",
    ("ip", False): """
        UNWIND $rows AS r MATCH (s:Skill {name: r.skill}) MATCH (rep:Report {url: r.report})
        MERGE (x:IP {addr: r.value}) MERGE (s)-[:DOWNLOADS_FROM]->(x) MERGE (x)-[:SOURCED_FROM]->(rep)""",
    ("ip", True): """
        UNWIND $rows AS r MATCH (s:Skill {name: r.skill}) MATCH (rep:Report {url: r.report})
        MERGE (x:CommonInfra {name: r.value}) SET x.kind = 'IP'
        MERGE (s)-[:DOWNLOADS_FROM]->(x) MERGE (x)-[:SOURCED_FROM]->(rep)""",
    ("payload", False): """
        UNWIND $rows AS r MATCH (s:Skill {name: r.skill}) MATCH (rep:Report {url: r.report})
        MERGE (x:PayloadString {value: r.value}) MERGE (s)-[:CONTAINS]->(x) MERGE (x)-[:SOURCED_FROM]->(rep)""",
}

_RESOLVE_QUERIES = {
    (False, False): """
        UNWIND $rows AS r MATCH (rep:Report {url: r.report})
        MERGE (d:Domain {name: r.domain}) MERGE (i:IP {addr: r.ip})
        MERGE (d)-[:RESOLVES_TO]->(i) MERGE (d)-[:SOURCED_FROM]->(rep) MERGE (i)-[:SOURCED_FROM]->(rep)""",
    (True, False): """
        UNWIND $rows AS r MATCH (rep:Report {url: r.report})
        MERGE (d:CommonInfra {name: r.domain}) SET d.kind = 'Domain' MERGE (i:IP {addr: r.ip})
        MERGE (d)-[:RESOLVES_TO]->(i) MERGE (i)-[:SOURCED_FROM]->(rep)""",
    (False, True): """
        UNWIND $rows AS r MATCH (rep:Report {url: r.report})
        MERGE (d:Domain {name: r.domain}) MERGE (i:CommonInfra {name: r.ip}) SET i.kind = 'IP'
        MERGE (d)-[:RESOLVES_TO]->(i) MERGE (d)-[:SOURCED_FROM]->(rep)""",
    (True, True): """
        UNWIND $rows AS r
        MERGE (d:CommonInfra {name: r.domain}) SET d.kind = 'Domain'
        MERGE (i:CommonInfra {name: r.ip}) SET i.kind = 'IP' MERGE (d)-[:RESOLVES_TO]->(i)""",
}


def counts(g=None) -> dict:
    g = g or get_graph()
    nodes = {row[0]: row[1] for row in g.query(
        "MATCH (n) UNWIND labels(n) AS l RETURN l, count(*) ORDER BY l").result_set}
    rels = {row[0]: row[1] for row in g.query(
        "MATCH ()-[r]->() RETURN type(r), count(r) ORDER BY type(r)").result_set}
    return {"nodes": nodes, "relationships": rels}


def main(argv: list[str]) -> int:
    args = [a for a in argv if not a.startswith("--")]
    data_dir = args[0] if args else "../data/"
    errors = validate(data_dir)
    if errors:
        print(f"{len(errors)} validation error(s) in {data_dir}:")
        for e in errors:
            print("  -", e)
        return 1
    print(f"0 validation errors. Loading {data_dir} into graph '{graph_name()}' ...")
    c = load_all(data_dir, reset="--reset" in argv)
    print("Nodes:")
    for k, v in c["nodes"].items():
        print(f"  {k:<14} {v}")
    print("Relationships:")
    for k, v in c["relationships"].items():
        print(f"  {k:<14} {v}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
